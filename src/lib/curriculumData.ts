export function getCurriculumsForGrade(grade?: string): CurriculumBook[] {
  if (!grade) return DEFAULT_CURRICULUMS;
  
  // Normalize match
  const filtered = DEFAULT_CURRICULUMS.filter(c => {
    if (grade.includes('الثالث الإعدادي') || grade.includes('التاسع') || grade.includes('إعدادي')) {
      return c.grade.includes('الإعدادي') || c.grade.includes('المتوسط') || c.grade.includes('التاسع');
    }
    if (grade.includes('الثانوي') || grade.includes('ثانوي')) {
      return c.grade.includes('الثانوي') || c.grade.includes('ثانوي');
    }
    return c.grade.includes(grade) || grade.includes(c.grade);
  });

  return filtered.length > 0 ? filtered : DEFAULT_CURRICULUMS;
}

export const SAMPLE_CURRICULUM_DATABASE = DEFAULT_CURRICULUMS;
export const getCurriculumBooksForGrade = getCurriculumsForGrade;
